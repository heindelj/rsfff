"""Slater-damped multipole fits (rsfff.qcgen.elst_fit): conventions and a synthetic recovery."""

import numpy as np
import torch

from rsfff.qcgen import elst_fit as F

D = F.DTYPE


def _sp(q=0.0, mu=(0, 0, 0), th=None, Z=1.0, b=2.0):
    return F.SiteParams(torch.tensor([q], dtype=D), torch.tensor([mu], dtype=D),
                        torch.zeros(1, 3, 3, dtype=D) if th is None else th[None], torch.tensor([Z], dtype=D),
                        torch.tensor([b], dtype=D))


P = torch.tensor([[0, 0, 3.0], [2.0, 1.0, 0.5], [-1.0, 2.0, -2.0]], dtype=D)
O = torch.zeros(1, 3, dtype=D)


def test_point_multipole_potentials():
    r = P.norm(dim=1)
    assert torch.allclose(F.potential(O, _sp(q=0.7), P, penetration=False), 0.7 / r)
    assert torch.allclose(F.potential(O, _sp(mu=(0, 0, 0.5)), P, penetration=False), 0.5 * P[:, 2] / r ** 3)
    th = torch.diag(torch.tensor([-0.5, -0.5, 1.0], dtype=D))
    assert torch.allclose(F.potential(O, _sp(th=th), P, penetration=False), (P @ th * P).sum(1) / r ** 5)


def test_slater_shell_penetration():
    # nucleus Z=1, shell -1 with a normalised exp(-b r) density
    r = P.norm(dim=1)
    ref = 1 / r - (1 - (1 + r) * torch.exp(-2 * r)) / r
    assert torch.allclose(F.potential(O, _sp(q=0.0, Z=1.0, b=2.0), P), ref)


def test_field_is_minus_grad_and_gradient_symmetric():
    sp = _sp(q=0.3, mu=(0.1, -0.2, 0.3), Z=2.0, b=1.7)
    phi, E, G = F.potential_field(O, sp, P, gradient=True, create_graph=False)
    h = 1e-5
    fd = torch.stack([-(F.potential(O, sp, P + h * e) - F.potential(O, sp, P - h * e)) / (2 * h) for e in torch.eye(3, dtype=D)], 1)
    assert torch.allclose(E, fd, atol=1e-8)
    assert torch.allclose(G, G.transpose(1, 2), atol=1e-10)


def test_pair_energy_symmetric():
    rng = np.random.default_rng(0)
    ca = torch.tensor(rng.normal(size=(3, 3)), dtype=D)
    cb = torch.tensor(rng.normal(size=(2, 3)) + [0, 0, 6.0], dtype=D)
    mk = lambda n: F.SiteParams(torch.tensor(rng.normal(size=n), dtype=D), torch.tensor(rng.normal(size=(n, 3)) * 0.1, dtype=D),
                                F.spherical_to_cartesian_quadrupole(torch.tensor(rng.normal(size=(n, 5)) * 0.1, dtype=D)),
                                torch.tensor(rng.uniform(1, 5, n), dtype=D), torch.tensor(rng.uniform(1.5, 3, n), dtype=D))
    a, b = mk(3), mk(2)
    assert torch.isclose(F.pair_energy(ca, a, cb, b), F.pair_energy(cb, b, ca, a))


def test_synthetic_recovery():
    """A grid generated by known parameters is refitted to the same potential."""
    X = torch.tensor([[0, 0, 0.12], [0, 1.43, -0.89], [0, -1.43, -0.89]], dtype=D)
    true = F.SiteParams(torch.tensor([-0.7, 0.35, 0.35], dtype=D), torch.tensor([[0, 0, 0.1], [0, 0.02, 0.0], [0, -0.02, 0.0]], dtype=D),
                        F.spherical_to_cartesian_quadrupole(torch.tensor([[0.2, 0, 0, 0.1, 0], [0] * 5, [0] * 5], dtype=D)),
                        torch.tensor([5.5, 0.7, 0.7], dtype=D), torch.tensor([2.4, 1.9, 1.9], dtype=D))
    from rsfff.qcgen.elst_db import surface_points, vdw_radii
    pts, sc = surface_points(X.numpy(), vdw_radii(["O", "H", "H"]), scales=(0.8, 1.2, 1.7, 2.5), density=0.8, rng=1)
    phi, E = F.potential_field(X, true, torch.tensor(pts, dtype=D), create_graph=False)
    grid = {"coords": X.numpy(), "points": pts, "scale": sc, "phi": phi.detach().numpy(), "field": E.detach().numpy()}
    mod, met = F.fit_monomer(grid, [8, 1, 1], 0, ridge=0.0, steps=300)
    # potentials converge fast; charges drift slowly along the charge<->atomic-dipole gauge, so the
    # check is on the potential and on the well-determined penetration parameters
    assert max(v["phi_rms"] / v["phi_ref_rms"] for v in met.values()) < 3e-3
    p = mod.params()
    assert torch.allclose(p.Z, true.Z, rtol=1e-2) and torch.allclose(p.b, true.b, rtol=1e-2)
