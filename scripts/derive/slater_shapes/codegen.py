import sympy as sp, pickle
from fractions import Fraction
d = pickle.load(open('tcpoly_K3.pkl', 'rb'))
a, b, ia, ib, w, R, Ea, Eb = sp.symbols('a b ia ib w R Ea Eb')
L = ['"""Generated by shape/codegen.py from shape/tc_poly.py (sympy) -- do not edit.',
     '',
     'Two-center overlap complements f_n (n = 1, 3, 5, 7, 9) between normalized shaped Slater densities',
     'N_k r^k e^{-a r} and N_l r^l e^{-b r}, k <= l <= 3:',
     '  closed form (a != b):  CLOSED[(k, l)](a, b, R, Ea, Eb) -> 5 orders, ia = 1/a, ib = 1/b, w = 1/(a^2 - b^2)',
     '  near-equal series:     f_n = e^{-u} sum_p eps^p S_p(u),  a = z(1+eps), b = z(1-eps), u = z R  (SERIES)',
     'Plain arithmetic only, so the functions accept torch tensors and mpmath numbers alike.',
     '"""', '']
for (k, l), out in sorted(d.items()):
    exprs = []
    for n in (1, 3, 5, 7, 9):
        Ca = {int(m): sp.sympify(c) for m, c in out[n]['Ca'].items()}
        Cb = {int(m): sp.sympify(c) for m, c in out[n]['Cb'].items()}
        exprs.append(Ea*sum(c*R**m for m, c in Ca.items()) + Eb*sum(c*R**m for m, c in Cb.items()))
    rep, red = sp.cse(exprs, symbols=sp.numbered_symbols('x'), optimizations='basic')
    body = [f'    {s} = {sp.pycode(ex, fully_qualified_modules=False)}' for s, ex in rep]
    ret = '    return (' + ', '.join(sp.pycode(x, fully_qualified_modules=False) for x in red) + ')'
    used = ' '.join(body) + ret
    L.append(f'def closed_{k}{l}(a, b, R, Ea, Eb):')
    if ' ia' in used or '(ia' in used or '*ia' in used:
        L.append('    ia = 1 / a')
    if ' ib' in used or '(ib' in used or '*ib' in used:
        L.append('    ib = 1 / b')
    L.append('    w = 1 / (a * a - b * b)')
    L.extend(body)
    L.append(ret)
    L.append('')
L.append('CLOSED = {' + ', '.join(f'({k}, {l}): closed_{k}{l}' for k, l in sorted(d)) + '}')
L.append('')
L.append('SERIES = {')
for (k, l), out in sorted(d.items()):
    L.append(f'    ({k}, {l}): (')
    for n in (1, 3, 5, 7, 9):
        rows = []
        for coeffs in out[n]['series']:
            rows.append('(' + ', '.join(repr(float(Fraction(c))) for c in coeffs) + ',)')
        L.append('        (' + ', '.join(rows) + '),')
    L.append('    ),')
L.append('}')
src = '\n'.join(L) + '\n'
src = src.replace('math.', '')
open('_slater_shape_tables.py', 'w').write(src)
print(len(src.splitlines()), 'lines', len(src)//1024, 'kB')
