"""Physically-parameterized bonded terms: Morse bonds, cosine angles, out-of-plane impropers.

This replaces the NN bond-energy head (:mod:`rsfff.ff.bond_energy`) with the pyCMM functional
forms whose *parameters* are generated by the conditioned network:

    V_bond(r)      = D [ (1 - e^{-beta (r - r_eq)})^2 - 1 ],    beta = sqrt(k / 2D)
    V_angle(theta) = (k_theta / 2) (cos theta - cos theta_eq)^2

Two deliberate choices relative to pyCMM (``~/dev/pyCMM/cmm/bonded.py``):

1. **The Morse is well-referenced** -- the ``- 1`` -- so the bond carries its dissociation
   energy: ``fragment_energy -> sum_i E0[Z_i]`` exactly as the bonds break, and ``D`` is the
   literal well depth rather than a shape parameter next to an unexplained constant. pyCMM's
   zero-at-minimum form pushes the atomization energy into terms that have nowhere physical
   to put it. (This is the one deviation from the user-specified literal formula, made so the
   isolated-fragment energy labels are representable at all.)
2. **No bilinear couplings and no explicit charge flux.** pyCMM needs bond-bond, stretch-bend
   and flux terms because its parameters are constants; here every parameter is a function of
   the fragment's geometry through the features, which carries those couplings implicitly.
   The geometry-independence regularizer (the ``delta_iso`` outputs below) is what keeps that
   flexibility from degenerating into "the parameters are a disguised pair energy".

``beta = sqrt(k / 2D)`` ties the harmonic curvature to the well depth (pyCMM
``system.py:712``), so the network predicts ``(r_eq, D, k)`` and the anharmonicity stays
physical by construction.

The bond/angle **topology comes from the fragment assignment and composition, never from a
distance rule** -- the same invariant the SQE channel graph keeps. Bonds are the heavy-H and
heavy-heavy pairs inside each fragment (H-H is never a bond); angles are enumerated from bonds
sharing an atom. A stretched bond therefore cannot fall out of its own term.

**Impropers (opt-in, ``impropers=True`` on the head).** Every atom with exactly three
bonded neighbors (the N of NH3, the O of H3O+) also carries one out-of-plane term per leg,
in the Wilson angle ``chi_l`` between leg ``l`` and the plane of the other two legs::

    s_l   = sin^2 chi_l = [b_l . (b_j x b_k)]^2 / |b_j x b_k|^2   (b: unit bonds from the center)
    V_imp = (k_chi / 2) s_l (s_l - 2 c_chi),        c_chi in (-1, 1),  k_chi > 0

i.e. ``(k_chi/2)[(s - c_chi)^2 - c_chi^2]``: zero at planarity, a polynomial in the squared
triple product. Three properties decide the form:

- **even in chi.** The two pyramidal minima of NH3 are mirror images and must be degenerate;
  a CHARMM-style harmonic improper ``k (omega - omega_0)^2`` with ``omega_0 != 0`` gives the
  inverted molecule a different energy (and depends on atom ordering), so it cannot
  describe inversion.
- **permutation-invariant.** Each leg's term is symmetric in its two in-plane partners, and
  all three legs are summed.
- **smooth everywhere the angle term is.** No ``asin``/``sqrt``; the only singular point is
  ``b_j || b_k`` (a linear J-center-K), guarded by an epsilon.

``c_chi`` is deliberately *not* confined to ``[0, 1]`` (it is not ``sin^2`` of an equilibrium
angle). ``c_chi > 0`` is a symmetric double well with minima at ``s = c_chi`` and a planar
barrier ``k c^2 / 2`` per leg; ``c_chi < 0`` is a pure restoring force toward planarity,
harmonic + quartic in ``chi`` (``k|c| s + k s^2 / 2``), which is also what an sp2 center would
use. For NH3 the second regime is the one that fits: the cosine angles alone already give a
double well, but its barrier, the umbrella (A1) frequency and the E bend all come from the
same ``(theta_eq, k_theta)`` and cannot all be right (constant parameters: A1 1158 vs 1022
cm^-1, E 1611 vs 1691). A planarizing improper (``c_chi ~ -0.5``) working against a more
pyramidal ``theta_eq`` (~101 deg) decouples them and reproduces HNH, both bends and the
5.9 kcal/mol barrier with constant parameters (``scripts/fit_bonded_priors_nh3.py``).

Units: this module works in **atomic units** throughout (bohr, hartree). The model converts
its Angstrom geometry once at the boundary.
"""

